// ============================================================================
// 26. utf8_read + utf8_write 往返: 全部 Unicode 平面边界
//     (注:0xFFFF 因 utf.c:191 `(c&0xFFFFFFFE)==0xFFFE` 被替换为 0xFFFD,
//     故不纳入往返用例。Surrogate 也类似,见单元测试 write_read_roundtrip)
// ============================================================================
#[test]
fn write_read_roundtrip_boundaries() {
    let cases: &[u32] = &[
        0x00, 0x7F, 0x80, 0x7FF, 0x800, 0xFFFD, 0xFFFE, 0x10000, 0x1F600, 0x10FFFF,
    ];
    for &c in cases {
        let mut buf = [0u8; 4];
        let n = utf8_write(&mut buf, c, 4);
        assert!((1..=4).contains(&n), "c={c:#x} wrote {n} bytes");
        let (decoded, n2) = utf8_read(&buf[..n]);
        assert_eq!(n, n2, "byte length roundtrip c={c:#x}");
        // 0xFFFD / 0xFFFE 的 3 字节形式读回都被归约为 0xFFFD
        let expected = if c == 0xFFFE { 0xFFFD } else { c };
        assert_eq!(decoded, expected, "codepoint roundtrip c={c:#x}");
    }
}

// ============================================================================
// 27. utf8_char_count: 空串 → 0 (utf.c:475-490 — r=0 初始)
// ============================================================================
#[test]
fn char_count_empty() {
    assert_eq!(utf8_char_count(b""), 0);
}

// ============================================================================
// 28. utf8_char_count: 全 ASCII (utf.c:486 `SQLITE_SKIP_UTF8`)
// ============================================================================
#[test]
fn char_count_ascii_only() {
    assert_eq!(utf8_char_count(b"hello world"), 11);
}

// ============================================================================
// 29. utf8_char_count: ASCII + 2/3/4 字节混合
// ============================================================================
#[test]
fn char_count_mixed_width() {
    // "a中b€c😀d" = 7 字符:ASCII, 3-byte, ASCII, 3-byte, ASCII, 4-byte, ASCII
    let s = "a中b€c😀d".as_bytes();
    assert_eq!(utf8_char_count(s), 7);
}

// ============================================================================
// 30. utf8_char_count: 遇到 NUL 提前停止 (utf.c:485 `while(*z!=0 ...)`)
// ============================================================================
#[test]
fn char_count_stops_at_nul() {
    let s: &[u8] = &[b'a', b'b', 0, b'c', b'd'];
    assert_eq!(utf8_char_count(s), 2);
}

// ============================================================================
// 31. utf8_char_count: 5 字节序列(无效)也算 1 个字符(对齐 SQLITE_SKIP_UTF8
//     宏的"消耗全部延续字节"语义)
// ============================================================================
#[test]
fn char_count_skips_invalid_continuation() {
    // 0xC2 + 单字节延续 = 2 字节"字符"
    let s: &[u8] = &[0xC2, 0xA0, 0xC2, 0xA0];
    assert_eq!(utf8_char_count(s), 2);
}
