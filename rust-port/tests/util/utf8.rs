//! `tests/util/utf8.rs` — `utf8_read` / `utf8_write` / `utf8_char_count`
//! 严格对齐 `sqlite-source/src/utf.c` 行为的集成测试。
//!
//! 每个测试在文档注释中标注对应的 C 源码行号与期望行为。
//! 行为差异(spec vs C)参见 `notes/T-0004-discovery.md`:
//! - overlong (>= 0x80) **被接受**(对齐 C,不替换为 0xFFFD)
//! - 5+ 字节序列因解码路径自然归约为 0xFFFD
//! - 起始字节 0x80-0xBF 视为单字节字面量

use libsqlite_rs::{utf8_char_count, utf8_read, utf8_write};

// ============================================================================
// 1. utf8_read: ASCII 单字节 (utf.c:189-191 — `c < 0x80` 路径)
// ============================================================================
#[test]
fn read_ascii_lowercase() {
    assert_eq!(utf8_read(b"a"), (0x61, 1));
}

// ============================================================================
// 2. utf8_read: ASCII NUL (utf.c:189-191 — NUL 走 <0xc0 路径)
// ============================================================================
#[test]
fn read_ascii_nul() {
    assert_eq!(utf8_read(&[0x00]), (0, 1));
}

// ============================================================================
// 3. utf8_read: 2 字节字符 U+00A0 (no-break space)
// ============================================================================
#[test]
fn read_two_byte_u00a0() {
    assert_eq!(utf8_read(&[0xC2, 0xA0]), (0x00A0, 2));
}

// ============================================================================
// 4. utf8_read: 2 字节字符 U+00FF (ÿ)
