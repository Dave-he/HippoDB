// ============================================================================
// 8. utf8_read: 4 字节字符 U+10FFFF (Unicode 码点上限)
// ============================================================================
#[test]
fn read_four_byte_u10ffff_max() {
    // U+10FFFF = 0xF4 0x8F 0xBF 0xBF
    let bytes = [0xF4, 0x8F, 0xBF, 0xBF];
    assert_eq!(utf8_read(&bytes), (0x10FFFF, 4));
}

// ============================================================================
// 9. utf8_read: 截断序列 — 起始字节为多字节但剩余不足
//     (utf.c:175-194 在 while 循环里用 `*pz & 0xc0 == 0x80` 终止;
//     C 端 *不* 把"短序列"判为非法 — 它只是消耗掉所有延续字节。
//     0xE4 0xB8 走 trans1[0x24]=0x04 → c = (4<<6)|0x38 = 0x138,是合法 ĸ。
//     真正的"FFFD 路径"见 0xC0 0x80 这种 overlong NUL 的测试)
// ============================================================================
#[test]
fn read_truncated_three_byte() {
    // 0xE4 + 1 延续字节 = 0x138 (ĸ),2 字节
    assert_eq!(utf8_read(&[0xE4, 0xB8]), (0x138, 2));
}

// ============================================================================
// 10. utf8_read: Surrogate 拒绝 — U+D800 (utf.c:190 `(c&0xFFFFF800)==0xD800`)
// ============================================================================
#[test]
fn read_surrogate_high_d800() {
    // U+D800 = 0xED 0xA0 0x80
    assert_eq!(utf8_read(&[0xED, 0xA0, 0x80]), (0xFFFD, 3));
}

// ============================================================================
// 11. utf8_read: Surrogate 拒绝 — U+DFFF (utf.c:190)
// ============================================================================
#[test]
fn read_surrogate_low_dfff() {
    // U+DFFF = 0xED 0xBF 0xBF
    assert_eq!(utf8_read(&[0xED, 0xBF, 0xBF]), (0xFFFD, 3));
}

// ============================================================================
// 12. utf8_read: 起始字节 0x80-0xBF 视为单字节 (utf.c:155-158)
// ============================================================================
#[test]
fn read_continuation_byte_as_leader() {
    assert_eq!(utf8_read(&[0x80]), (0x80, 1));
    assert_eq!(utf8_read(&[0xBF, 0xBF]), (0xBF, 1));
}

// ============================================================================
// 13. utf8_read: 5+ 字节起始字节自然归约到 FFFD (utf.c:189-191)
// ============================================================================
#[test]
fn read_five_byte_leader_reduces_to_fffd() {
    // 0xF8 (trans1[0x38]=0x00) 后跟若干延续字节,c 永远 <0x80 → FFFD
    assert_eq!(utf8_read(&[0xF8, 0x80, 0x80, 0x80, 0x80, 0x80]), (0xFFFD, 6));
}

// ============================================================================
// 14. utf8_read: overlong NUL (0xC0 0x80) → FFFD (utf.c:189-191 c<0x80)
// ============================================================================
#[test]
fn read_overlong_nul_reduces_to_fffd() {
    assert_eq!(utf8_read(&[0xC0, 0x80]), (0xFFFD, 2));
}

// ============================================================================
// 15. utf8_read: 非字符 U+FFFE 替换为 FFFD (utf.c:191 `(c&0xFFFFFFFE)==0xFFFE`)
// ============================================================================
#[test]
fn read_noncharacter_fffe_reduces_to_fffd() {
    // U+FFFE = 0xEF 0xBF 0xBE
    assert_eq!(utf8_read(&[0xEF, 0xBF, 0xBE]), (0xFFFD, 3));
}

